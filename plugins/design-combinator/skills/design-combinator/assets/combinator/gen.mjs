#!/usr/bin/env node
// design-combinator generator — config-driven, generalized from the earlier
// per-wedge combinator generator (which hardcoded one page's paths, a fixed
// font array, and brittle exact-string anchors).
//
// Usage: node gen.mjs <configPath> <targetHtmlPath> <outDir>
//
// Reads combinator.config.json (see references/config-schema.md) + the target
// page's HTML, and writes into <outDir>:
//   combinator.data.js     — window.CMB = { meta, dims, defaults, multi, jump, variantRegistry }
//   combinator.effects.css — generated html[data-k=v]{…} rules from token/component options
//   combinator.html        — target page with fonts/dock/effects injected

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

function main() {
  const [, , configPath, targetHtmlPath, outDir] = process.argv;
  if (!configPath || !targetHtmlPath || !outDir) {
    throw new Error('usage: node gen.mjs <configPath> <targetHtmlPath> <outDir>');
  }

  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  const targetHtml = readFileSync(targetHtmlPath, 'utf8');
  const meta = config.meta;

  // Dim keys round-trip through element.dataset (which camelCase→kebab-cases),
  // HTML attribute names (lowercased), and CSS attribute selectors. Those three
  // only agree for lowercase kebab-case keys: a camelCase key like "bodyFont"
  // silently no-ops — dataset writes `data-body-font`, but the generated selector
  // reads `data-bodyfont`, and they never match. Reject non-conforming keys loudly
  // rather than emit a silently-dead dim.
  const badKeys = [];
  for (const category of config.categories) {
    for (const dim of category.dims) {
      if (!/^[a-z][a-z0-9-]*$/.test(dim.key)) badKeys.push(dim.key);
    }
  }
  if (badKeys.length) {
    throw new Error(
      'design-combinator gen: dim keys must be lowercase kebab-case (match /^[a-z][a-z0-9-]*$/) — ' +
      'they round-trip through dataset / HTML attributes / CSS selectors, which agree only for that form. ' +
      'Offending key(s): ' + JSON.stringify(badKeys)
    );
  }

  mkdirSync(outDir, { recursive: true });

  const dataJs = buildDataJs(config);
  const effectsCss = buildEffectsCss(config);
  const html = buildHtml(targetHtml, meta);

  writeFileSync(outDir + '/combinator.data.js', dataJs);
  writeFileSync(outDir + '/combinator.effects.css', effectsCss);
  writeFileSync(outDir + '/combinator.html', html);

  console.log('design-combinator gen: wrote combinator.data.js, combinator.effects.css, combinator.html to', outDir);
}

/* ---------------------------------------------------------------------
 * 1. combinator.data.js — flat dim catalog + defaults/multi/jump/registry
 * ------------------------------------------------------------------- */

function buildDataJs(config) {
  const dims = [];
  const variantRegistry = {};

  for (const category of config.categories) {
    for (const dim of category.dims) {
      dims.push({
        key: dim.key,
        label: dim.label,
        cat: category.cat,
        icon: category.icon,
        mechanism: dim.mechanism,
        cssVars: dim.cssVars,
        target: dim.target,
        multi: !!dim.multi,
        default: dim.default,
        jumpSelector: dim.jumpSelector,
        options: dim.options.map((o) => ({ name: o.name, rationale: o.rationale }))
      });

      if (dim.mechanism === 'markup') {
        const registry = {};
        for (const opt of dim.options) {
          // the `current`/default option is captured live by the runtime
          // (original outerHTML at load time) — never bake it here.
          if (opt.name === dim.default) continue;
          registry[opt.name] = opt.html;
        }
        variantRegistry[dim.key] = registry;
      }
    }
  }

  const defaults = {};
  const multi = {};
  const jump = {};
  for (const d of dims) {
    defaults[d.key] = d.default;
    if (d.multi) multi[d.key] = true;
    jump[d.key] = d.jumpSelector;
  }

  const payload = { meta: config.meta, dims, defaults, multi, jump, variantRegistry };

  return (
    '/* AUTO-GENERATED by design-combinator gen.mjs — do not edit by hand */\n' +
    'window.CMB = ' + JSON.stringify(payload, null, 2) + ';\n'
  );
}

/* ---------------------------------------------------------------------
 * 2. combinator.effects.css — token/component options as attr-scoped rules
 * ------------------------------------------------------------------- */

function buildEffectsCss(config) {
  const lines = ['/* AUTO-GENERATED by design-combinator gen.mjs — do not edit by hand */'];

  for (const category of config.categories) {
    for (const dim of category.dims) {
      const attrOp = dim.multi ? '~=' : '=';

      if (dim.mechanism === 'token') {
        for (const opt of dim.options) {
          if (!opt.vars) continue;
          lines.push(`/* ${dim.key}: ${opt.name} */`);
          lines.push(tokenRule(dim.key, opt.name, opt.vars, attrOp));
        }
      } else if (dim.mechanism === 'component') {
        for (const opt of dim.options) {
          const rules = componentRules(dim.key, opt.name, opt.css, attrOp);
          if (!rules.length) continue;
          lines.push(`/* ${dim.key}: ${opt.name} */`);
          lines.push(...rules);
        }
      }
      // markup options emit nothing here — they go to variantRegistry.
    }
  }

  return lines.join('\n') + '\n';
}

function tokenRule(key, optName, vars, attrOp) {
  const decls = Object.entries(vars)
    .map(([varName, val]) => `${varName}:${val}`)
    .join('; ');
  return `html[data-${key}${attrOp}"${optName}"]{ ${decls} }`;
}

function componentRules(key, optName, css, attrOp) {
  if (!css || !css.trim()) return [];
  const rules = [];
  const ruleRe = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = ruleRe.exec(css))) {
    const selectors = m[1]
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean);
    const decls = m[2];
    const prefixed = selectors
      .map((sel) => `html[data-${key}${attrOp}"${optName}"] ${sel}`)
      .join(', ');
    rules.push(`${prefixed}{${decls}}`);
  }
  return rules;
}

/* ---------------------------------------------------------------------
 * 3. combinator.html — target page + injected fonts/icons/dock/data/js
 * ------------------------------------------------------------------- */

function buildHtml(targetHtml, meta) {
  const anchors = meta.insertAnchors || {};
  if (!anchors.headEnd || !targetHtml.includes(anchors.headEnd)) {
    throw new Error(
      `design-combinator gen: insertAnchors.headEnd not found in target HTML: ${JSON.stringify(anchors.headEnd)}`
    );
  }
  if (!anchors.bodyEnd || !targetHtml.includes(anchors.bodyEnd)) {
    throw new Error(
      `design-combinator gen: insertAnchors.bodyEnd not found in target HTML: ${JSON.stringify(anchors.bodyEnd)}`
    );
  }

  const headEndIdx = targetHtml.indexOf(anchors.headEnd);
  const bodyEndIdx = targetHtml.indexOf(anchors.bodyEnd);

  // cssLink is optional: inject right after it so the effects/dock CSS wins
  // the cascade; if it's absent (or doesn't match this exact page), fall
  // back to injecting just before headEnd.
  let headInsertPos = headEndIdx;
  if (anchors.cssLink) {
    const cssLinkIdx = targetHtml.indexOf(anchors.cssLink);
    if (cssLinkIdx !== -1) headInsertPos = cssLinkIdx + anchors.cssLink.length;
  }

  const fontsUrl = buildFontsUrl(meta.fontFamilies || []);
  const headBlock =
    '\n' +
    `<link href="${fontsUrl}" rel="stylesheet">\n` +
    `<link rel="stylesheet" href="https://unpkg.com/@phosphor-icons/web@2.1.1/src/regular/style.css">\n` +
    `<link rel="stylesheet" href="dock.css">\n` +
    `<link rel="stylesheet" href="combinator.effects.css">\n`;

  const bodyBlock =
    '\n' +
    `<div id="cmb-dock"></div>\n` +
    `<div id="cmb-fab"></div>\n` +
    `<script src="combinator.data.js"></script>\n` +
    `<script src="dock.js"></script>\n`;

  // headInsertPos is always <= bodyEndIdx for well-formed HTML (head closes
  // before body), so slicing against the original indices is safe without
  // recomputing offsets after the first splice.
  return (
    targetHtml.slice(0, headInsertPos) +
    headBlock +
    targetHtml.slice(headInsertPos, bodyEndIdx) +
    bodyBlock +
    targetHtml.slice(bodyEndIdx)
  );
}

function buildFontsUrl(fontFamilies) {
  const families = fontFamilies.map((f) => 'family=' + f.replace(/ /g, '+')).join('&');
  return 'https://fonts.googleapis.com/css2?' + families + '&display=swap';
}

main();
